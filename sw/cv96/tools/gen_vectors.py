#!/usr/bin/env python3
"""Embed the testbench vectors (sim/vectors/) into a C header for snn_test, so the
board needs only one file.   gen_vectors.py <vector_dir> <out.h>"""
import os, sys

vdir, out = sys.argv[1], sys.argv[2]
frames = []
for line in open(os.path.join(vdir, "frames.txt")):
    t = line.split()
    if t:
        n = int(t[0]); frames.append(bytes(int(x, 16) for x in t[1:1 + n]))
exp = [l.split() for l in open(os.path.join(vdir, "expected.txt")) if l.strip()]
cfg = [l.split() for l in open(os.path.join(vdir, "cfg.txt")) if l.strip()]
assert len(frames) == len(exp)

o = ["/* generated by gen_vectors.py from sim/vectors/ - do not edit */",
     "#include <stdint.h>",
     "#define VEC_N %d" % len(frames), "#define CFG_N %d" % len(cfg)]
blob = b"".join(frames)
o.append("static const uint8_t vec_bytes[%d] = {" % len(blob))
for i in range(0, len(blob), 24):
    o.append("  " + ",".join("0x%02x" % b for b in blob[i:i + 24]) + ",")
o.append("};")
offs, p = [], 0
for f in frames:
    offs.append(p); p += len(f)
o.append("static const uint32_t vec_off[VEC_N] = {%s};" % ",".join(map(str, offs)))
o.append("static const uint16_t vec_len[VEC_N] = {%s};" % ",".join(str(len(f)) for f in frames))
o.append("/* golden model answers: mal, cnt0, cnt1, ground-truth label, attack kind */")
o.append("static const uint8_t exp_mal[VEC_N]  = {%s};" % ",".join(e[3] for e in exp))
o.append("static const uint8_t exp_c0[VEC_N]   = {%s};" % ",".join(e[1] for e in exp))
o.append("static const uint8_t exp_c1[VEC_N]   = {%s};" % ",".join(e[2] for e in exp))
o.append("static const uint8_t exp_lab[VEC_N]  = {%s};" % ",".join(e[4] for e in exp))
o.append("static const char *const exp_kind[VEC_N] = {%s};" % ",".join('"%s"' % e[5] for e in exp))
o.append("static const uint16_t cfg_addr[CFG_N] = {%s};" % ",".join("0x" + c[0] for c in cfg))
o.append("static const uint32_t cfg_data[CFG_N] = {%s};" % ",".join("0x" + c[1] + "u" for c in cfg))
open(out, "w").write("\n".join(o) + "\n")
print("wrote %s: %d frames (%d bytes), %d config words" % (out, len(frames), len(blob), len(cfg)))
